function mulberry(seed: number) {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function buildSeedResources(now = Date.now()): Resource[] {
  const rnd = mulberry(20260214);
  const out: Resource[] = [];
  let seq = 0;

  for (const dept of DEPARTMENTS) {
    const specs = DEPT_SPECS[dept.id] ?? [];
    const target = DEPT_TARGETS[dept.id] ?? 0;
    let num = 0;

    outer: for (const spec of specs) {
      const variants = spec.s.length ? spec.s : [""];
      for (const v of variants) {
        if (num >= target) break outer;
        num++;
        seq++;
        const r1 = rnd();
        const r2 = rnd();
        const r3 = rnd();
        const minQty = 4 + Math.round(r2 * 10);
        let qty = Math.round((10 + r1 * 95) * (QTY_MULT[dept.id] ?? 1));
        if (seq % 23 === 5) qty = 0;
        else if (seq % 13 === 4) qty = minQty;
        const price = Math.max(1, Math.round((PRICE_BASE[dept.id] ?? 15) * (0.4 + r3 * 2.6)));
        out.push({
          id: `${dept.id}-${num}`,
          name: v ? `${spec.n} ${v}` : spec.n,
          sku: `${dept.skuPrefix}-${String(num).padStart(3, "0")}`,
          categoryId: dept.id,
          qty,
          minQty,
          unit: spec.u,
          price,
          location: `منطقة ${ZONES[(num - 1) % ZONES.length]} · رف ${((num - 1) % 6) + 1}`,
          createdAt: now - Math.round(r2 * 90) * 864e5,
          updatedAt: now - Math.round(r1 * 12) * 864e5,
        });
      }
    }
  }
  return out;
}

